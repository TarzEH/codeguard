#!/usr/bin/env bash
#
# codeguard installer.
#
#   ./install.sh              full install: secrets, cluster, CLI, smoke test
#   ./install.sh --no-cli     skip installing the CLI into /usr/local/bin
#   ./install.sh --cli-only   only (re)install the CLI
#   ./install.sh --uninstall  stop the cluster and remove the CLI
#
set -uo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CLI_TARGET="${CLI_TARGET:-/usr/local/bin/codeguard}"
ENV_FILE="$REPO_DIR/.env"
READY_TIMEOUT="${READY_TIMEOUT:-300}"

INSTALL_CLI=1
CLI_ONLY=0
UNINSTALL=0

if [ -t 1 ] && [ -z "${NO_COLOR:-}" ]; then
    B=$'\033[1m'; R=$'\033[0m'; DIM=$'\033[2m'
    OK=$'\033[1;32m'; WARN=$'\033[1;33m'; ERR=$'\033[1;31m'; ACC=$'\033[1;36m'
else
    B=""; R=""; DIM=""; OK=""; WARN=""; ERR=""; ACC=""
fi

step()  { printf '\n%s==>%s %s%s%s\n' "$ACC" "$R" "$B" "$1" "$R"; }
ok()    { printf '  %s✓%s %s\n' "$OK" "$R" "$1"; }
warn()  { printf '  %s!%s %s\n' "$WARN" "$R" "$1"; }
die()   { printf '\n  %s✗ %s%s\n\n' "$ERR" "$1" "$R" >&2; exit 1; }

for arg in "$@"; do
    case "$arg" in
        --no-cli)    INSTALL_CLI=0 ;;
        --cli-only)  CLI_ONLY=1 ;;
        --uninstall) UNINSTALL=1 ;;
        -h|--help)   sed -n '2,10p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *)           die "unknown option: $arg" ;;
    esac
done

banner() {
    printf '\n%s' "$ACC"
    cat <<'EOF'
                 _                                  _
   ___ ___    __| | ___  __ _ _   _  __ _ _ __ __| |
  / __/ _ \  / _` |/ _ \/ _` | | | |/ _` | '__/ _` |
 | (_| (_) || (_| |  __/ (_| | |_| | (_| | | | (_| |
  \___\___/  \__,_|\___|\__, |\__,_|\__,_|_|  \__,_|
                        |___/
EOF
    printf '%s  distributed dependency vulnerability scanner%s\n' "$DIM" "$R"
}

# --------------------------------------------------------------------- uninstall
if [ "$UNINSTALL" = "1" ]; then
    banner
    step "Stopping the cluster"
    (cd "$REPO_DIR" && docker compose --profile autoscale down --remove-orphans) && ok "cluster stopped"
    step "Removing the CLI"
    if [ -f "$CLI_TARGET" ]; then
        if [ -w "$(dirname "$CLI_TARGET")" ]; then rm -f "$CLI_TARGET"; else sudo rm -f "$CLI_TARGET"; fi
        ok "removed $CLI_TARGET"
    else
        warn "$CLI_TARGET not present"
    fi
    printf '\n  %sVolumes were kept.%s Remove them with: docker compose down -v\n\n' "$DIM" "$R"
    exit 0
fi

# ------------------------------------------------------------------------ CLI
install_cli() {
    step "Installing the CLI"
    local source="$REPO_DIR/src/cli/codeguard.sh"
    [ -f "$source" ] || die "cannot find $source"

    local dir; dir="$(dirname "$CLI_TARGET")"
    [ -d "$dir" ] || die "$dir does not exist"

    if [ -w "$dir" ]; then
        install -m 0755 "$source" "$CLI_TARGET"
    else
        warn "$dir needs elevated permissions"
        sudo install -m 0755 "$source" "$CLI_TARGET" || die "could not install the CLI"
    fi
    ok "installed $CLI_TARGET ($("$CLI_TARGET" -v))"

    command -v codeguard >/dev/null 2>&1 \
        || warn "$dir is not on your PATH - add it to use \`codeguard\` directly"
}

if [ "$CLI_ONLY" = "1" ]; then
    banner; install_cli; printf '\n'; exit 0
fi

banner

# --------------------------------------------------------------- prerequisites
step "Checking prerequisites"
missing=0
require() {
    if command -v "$1" >/dev/null 2>&1; then
        ok "$1"
    else
        warn "$1 is missing - $2"
        missing=1
    fi
}
require docker   "https://www.docker.com/"
require jq       "https://stedolan.github.io/jq/"
require curl     "usually preinstalled"
require openssl  "needed to generate secrets"

if docker compose version >/dev/null 2>&1; then
    ok "docker compose"
else
    warn "docker compose v2 is missing"
    missing=1
fi
docker info >/dev/null 2>&1 || die "the Docker daemon is not running"
[ "$missing" = "0" ] || die "install the missing prerequisites and re-run"

command -v pipreqs >/dev/null 2>&1 \
    || warn "pipreqs not found (optional - without it, scans read requirements.txt directly)"

# --------------------------------------------------------------------- secrets
step "Configuring secrets"
if [ -f "$ENV_FILE" ]; then
    ok ".env already exists - keeping it"
else
    # Alphanumeric on purpose: these go into a MongoDB connection URI, where
    # unescaped punctuation would have to be percent-encoded.
    gen() { LC_ALL=C openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c 24; }
    umask 077
    cat > "$ENV_FILE" <<EOF
# Generated by install.sh - keep this file out of version control.
MONGO_ROOT_USERNAME=codeguard_root
MONGO_ROOT_PASSWORD=$(gen)
MONGO_APP_USERNAME=codeguard_app
MONGO_APP_PASSWORD=$(gen)
MONGO_DB=codeguard
HAPROXY_STATS_PASSWORD=$(gen)

# Backend replicas at startup. The autoscaler grows this on load.
BACKEND_REPLICAS=1
MIN_REPLICAS=1
MAX_REPLICAS=12
EOF
    chmod 600 "$ENV_FILE"
    ok "generated .env with random credentials (mode 600)"
fi

# --------------------------------------------------------------------- cluster
step "Building and starting the cluster"
printf '  %sthis takes about a minute on a cold start%s\n' "$DIM" "$R"
(cd "$REPO_DIR" && docker compose up -d --build) >/dev/null 2>&1 \
    || die "docker compose failed - run 'docker compose up -d --build' to see why"
ok "containers started"

step "Waiting for the cluster to be ready"
deadline=$(( $(date +%s) + READY_TIMEOUT ))
ready=0
while [ "$(date +%s)" -lt "$deadline" ]; do
    if curl -sf -o /dev/null --max-time 3 http://127.0.0.1:80/health 2>/dev/null; then
        ready=1; break
    fi
    printf '.'; sleep 3
done
printf '\n'
[ "$ready" = "1" ] || die "cluster did not become ready in ${READY_TIMEOUT}s (try: docker compose logs)"

health=$(curl -s http://127.0.0.1:80/health)
ok "backend healthy (node $(printf '%s' "$health" | jq -r .node))"
ok "zookeeper $(printf '%s' "$health" | jq -r .zookeeper), mongo $(printf '%s' "$health" | jq -r .mongo)"

# ------------------------------------------------------------------ smoke test
step "Running a smoke test"
vulnerable=$(curl -s --max-time 60 -X POST http://127.0.0.1:80/scan \
    -H 'Content-Type: application/json' \
    -d '{"dependencies":["flask==2.2.2"]}' | jq -r '.vulnerable // "error"')
if [ "$vulnerable" = "error" ] || [ -z "$vulnerable" ]; then
    die "the smoke scan failed - check 'docker compose logs backend'"
fi
[ "$vulnerable" -gt 0 ] \
    && ok "scanned flask==2.2.2 - $vulnerable vulnerable package reported" \
    || warn "flask==2.2.2 reported clean, which is unexpected"

[ "$INSTALL_CLI" = "1" ] && install_cli

# ----------------------------------------------------------------------- done
printf '\n%s%s Installation complete.%s\n\n' "$OK" "✓" "$R"
cat <<EOF
  ${B}Scan a project${R}
    cd /path/to/project && codeguard

  ${B}Grow with load${R}
    docker compose --profile autoscale up -d

  ${B}Operate${R}
    make status          cluster overview
    make logs            follow logs
    make test            unit tests
    make failover-test   prove leader re-election
    make down            stop everything

  ${DIM}Secrets are in .env (git-ignored). HAProxy stats: http://127.0.0.1:8404${R}

EOF
